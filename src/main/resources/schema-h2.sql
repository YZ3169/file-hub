-- file-hub 桌面版建表脚本（H2）
--
-- 与 schema.sql 的 MySQL 版本结构一一对应，差异只在语法：
-- 没有 CREATE DATABASE/USE、反引号、ENGINE、COMMENT、FULLTEXT；
-- 主键用标准 IDENTITY；用户名用 VARCHAR_IGNORECASE 保持 MySQL 的
-- utf8mb4_general_ci 大小写不敏感语义。
--
-- 每次启动都会执行；所有语句必须幂等（IF NOT EXISTS），不能 DROP 用户数据。

CREATE TABLE IF NOT EXISTS user_account
(
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      VARCHAR_IGNORECASE(32) NOT NULL,
    password_hash VARCHAR(100)           NOT NULL,
    role          VARCHAR(16)            NOT NULL DEFAULT 'USER',
    enabled       TINYINT                NOT NULL DEFAULT 1,
    created_at    TIMESTAMP              NOT NULL,
    updated_at    TIMESTAMP              NOT NULL,
    CONSTRAINT uk_username UNIQUE (username)
);

CREATE TABLE IF NOT EXISTS user_session
(
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      BIGINT    NOT NULL,
    token_hash   CHAR(64)  NOT NULL,
    expires_at   TIMESTAMP NOT NULL,
    created_at   TIMESTAMP NOT NULL,
    last_used_at TIMESTAMP DEFAULT NULL,
    CONSTRAINT uk_token_hash UNIQUE (token_hash)
);
CREATE INDEX IF NOT EXISTS idx_session_user ON user_session (user_id);
CREATE INDEX IF NOT EXISTS idx_session_expires ON user_session (expires_at);

CREATE TABLE IF NOT EXISTS download_ticket
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_hash CHAR(64)    NOT NULL,
    file_id     VARCHAR(64) NOT NULL,
    user_id     BIGINT      NOT NULL,
    expires_at  TIMESTAMP   NOT NULL,
    created_at  TIMESTAMP   NOT NULL,
    CONSTRAINT uk_ticket_hash UNIQUE (ticket_hash)
);
CREATE INDEX IF NOT EXISTS idx_ticket_expires ON download_ticket (expires_at);

-- 一行 = 一个逻辑文件；秒传命中时多行共享同一个 storage_path。
CREATE TABLE IF NOT EXISTS file_info
(
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    file_id      VARCHAR(64)   NOT NULL,
    file_name    VARCHAR(255)  NOT NULL,
    file_size    BIGINT        NOT NULL,
    file_hash    CHAR(64)      NOT NULL,
    chunk_size   INT           NOT NULL,
    chunk_total  INT           NOT NULL,
    storage_path VARCHAR(500)  DEFAULT NULL,
    status       TINYINT       NOT NULL DEFAULT 0,
    owner_id     BIGINT        DEFAULT NULL,
    create_time  TIMESTAMP     NOT NULL,
    update_time  TIMESTAMP     NOT NULL,
    CONSTRAINT uk_file_id UNIQUE (file_id)
);
CREATE INDEX IF NOT EXISTS idx_hash_size_status ON file_info (file_hash, file_size, status);
CREATE INDEX IF NOT EXISTS idx_storage_path ON file_info (storage_path);
CREATE INDEX IF NOT EXISTS idx_status_update ON file_info (status, update_time);
CREATE INDEX IF NOT EXISTS idx_status_id ON file_info (status, id);
CREATE INDEX IF NOT EXISTS idx_owner_status_id ON file_info (owner_id, status, id);
CREATE INDEX IF NOT EXISTS idx_owner_hash_size_status ON file_info (owner_id, file_hash, file_size, status);

CREATE TABLE IF NOT EXISTS file_chunk
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    file_id     VARCHAR(64) NOT NULL,
    chunk_index INT         NOT NULL,
    chunk_size  INT         NOT NULL,
    chunk_hash  CHAR(64)    DEFAULT NULL,
    create_time TIMESTAMP   NOT NULL,
    CONSTRAINT uk_file_chunk UNIQUE (file_id, chunk_index)
);

-- 分享：链接 + 4 位提取码；只存提取码的 BCrypt 摘要。
CREATE TABLE IF NOT EXISTS file_share
(
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    share_token     VARCHAR(64)  NOT NULL,
    file_id         VARCHAR(64)  NOT NULL,
    owner_id        BIGINT       NOT NULL,
    code_hash       VARCHAR(100) NOT NULL,
    expires_at      TIMESTAMP    DEFAULT NULL,
    status          TINYINT      NOT NULL DEFAULT 1,
    download_count  BIGINT       NOT NULL DEFAULT 0,
    failed_attempts INT          NOT NULL DEFAULT 0,
    locked_until    TIMESTAMP    DEFAULT NULL,
    create_time     TIMESTAMP    NOT NULL,
    update_time     TIMESTAMP    NOT NULL,
    CONSTRAINT uk_share_token UNIQUE (share_token)
);
CREATE INDEX IF NOT EXISTS idx_share_owner ON file_share (owner_id, id);
CREATE INDEX IF NOT EXISTS idx_share_file ON file_share (file_id);
CREATE INDEX IF NOT EXISTS idx_share_status_expires ON file_share (status, expires_at);
CREATE INDEX IF NOT EXISTS idx_share_update_time ON file_share (update_time);
CREATE INDEX IF NOT EXISTS idx_share_expires ON file_share (expires_at);
